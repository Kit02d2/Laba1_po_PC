#include <stdio.h>
#include <math.h>
#include <locale.h>

int main() {
    // Настройка русской локализации для корректного вывода букв в консоли
    setlocale(LC_ALL, "Russian");

    double a, b, c, x, fx;

    // Ввод всех четырех параметров одной строкой
    printf("Введите через пробел значения a, b, c, x: ");
    if (scanf("%lf %lf %lf %lf", &a, &b, &c, &x) != 4) {
        printf("Ошибка ввода данных!\n");
        return 1;
    }

    // Условие 1: (x + a < 0) и (c == 0)
    if ((x + a) < 0 && c == 0) {
        // Проверка деления на ноль в выражении 1/(a*x)
        if (a * x == 0) {
            printf("Ошибка: деление на ноль в выражении 1/(a*x)\n");
            return 1;
        }
        fx = 1.0 / (a * x) - b;
    }
    // Условие 2: (x + a > 0) и (c != 0)
    else if ((x + a) > 0 && c != 0) {
        // Проверка деления на ноль в выражении (x - a)/sin(x)
        if (sin(x) == 0) {
            printf("Ошибка: деление на ноль в выражении (x - a)/sin(x)\n");
            return 1;
        }
        fx = (x - a) / sin(x);
    }
    // Условие 3: во всех остальных случаях
    else {
        // Проверка деления на ноль в выражении (10*x)/(c - 6)
        if (c == 6) {
            printf("Ошибка: деление на ноль в выражении (10*x)/(c - 6)\n");
            return 1;
        }
        fx = (10.0 * x) / (c - 6);
    }

    // Вывод результатов с точностью до 5 знаков после запятой
    printf("\n----------------------------------------\n");
    printf("Аргумент x = %.5lf\n", x);
    printf("Значение функции f(x) = %.5lf\n", fx);
    printf("----------------------------------------\n");

    return 0;
}